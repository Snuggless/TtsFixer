namespace TtsFixer.WebApp;

/// <summary>
/// Provides predefined route templates for use in application routing.
/// </summary>
/// <remarks>This class contains constants representing common route paths used in web applications.  These
/// templates can be used to standardize routing definitions across the application.</remarks>
internal static class RouteTemplate
{
    /// <summary>
    /// Represents the root index path used in routing.
    /// </summary>
    /// <remarks>This constant is typically used to define the default route or the base path in web
    /// applications.</remarks>
    public const string Index = "/";

    /// <summary>
    /// Represents the route path for the "About" page.
    /// </summary>
    public const string About = "/about";
}
